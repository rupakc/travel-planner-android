package io.github.rupakc.travelplanner.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Fails a build whose app does not bind every `@HiltViewModel` declared in the project (see [HiltViewModelGuard]).
 * Wired by `travelplanner.android.application` so `assemble`/`bundle`/`package<Variant>` of every variant depend on it;
 * minified variants also get the R8 dex check.
 */
@CacheableTask
abstract class VerifyHiltViewModelsTask : DefaultTask() {
    /** Kotlin/Java sources of every module's shipping source sets for this variant (main, flavour, build type, variant). */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    /** Java sources generated by `hiltJavaCompile<Variant>` (contains `*_HiltComponents_SingletonC.java`). */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val componentSources: ConfigurableFileCollection

    /** R8 `mapping.txt` of the variant; absent for non-minified variants, which skip the dex check. */
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val mappingFile: RegularFileProperty

    /** Dex files written by R8 (`minify<Variant>WithR8`), i.e. exactly what is packaged. Only read with [mappingFile]. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val dexFiles: ConfigurableFileCollection

    @get:Input
    abstract val variantName: Property<String>

    /** Lists the ViewModels checked; also makes the task up to date when nothing changed. */
    @get:OutputFile
    abstract val report: RegularFileProperty

    @TaskAction
    fun verify() {
        val viewModels =
            sources.files.filter { it.extension == "kt" || it.extension == "java" }
                .flatMap { HiltViewModelGuard.findHiltViewModels(it.readText()) }
                .toSortedSet()
        if (viewModels.isEmpty()) fail("Hilt ViewModel guard found no @HiltViewModel classes; the source scan is broken")

        val components = componentSources.asFileTree.files.filter { it.name.endsWith("_HiltComponents_SingletonC.java") }
        if (components.isEmpty()) fail("Hilt ViewModel guard found no *_HiltComponents_SingletonC.java in $componentSources")
        val missingInComponent =
            components.map { HiltViewModelGuard.missingFromComponent(viewModels, it.readText()) }
                .reduce { acc, missing -> acc.intersect(missing.toSet()).toList() }

        val missingInDex = if (mappingFile.isPresent) missingFromDex(viewModels) else emptyList()

        if (missingInComponent.isNotEmpty() || missingInDex.isNotEmpty()) {
            fail(HiltViewModelGuard.failureMessage(variantName.get(), missingInComponent, missingInDex))
        }
        report.get().asFile.writeText(viewModels.joinToString("\n", postfix = "\n"))
        logger.lifecycle("Hilt ViewModel guard: all ${viewModels.size} @HiltViewModel classes bound in ${variantName.get()}")
    }

    private fun missingFromDex(viewModels: Collection<String>): List<String> {
        val mapping = mappingFile.get().asFile.useLines { HiltViewModelGuard.parseMapping(it) }
        val dex = dexFiles.files.filter { it.extension == "dex" }
        if (dex.isEmpty()) fail("Hilt ViewModel guard found no R8 dex output")
        val strings = dex.flatMapTo(HashSet()) { HiltViewModelGuard.dexStrings(it.readBytes()) }
        return HiltViewModelGuard.missingFromDex(viewModels, mapping, strings)
    }

    private fun fail(message: String): Nothing = throw GradleException(message)
}
