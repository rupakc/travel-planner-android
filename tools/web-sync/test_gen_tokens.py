import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import gen_tokens  # noqa: E402

FIXTURE = Path(__file__).parent / "fixtures" / "tokens_min.json"
SHA = "e8c78cb600e1e25bc5778ee42bc03333ad05c530"


def _tokens():
    return json.loads(FIXTURE.read_text())


class GenTokensTest(unittest.TestCase):
    def test_names_and_hex(self):
        out = gen_tokens.render_palette(_tokens(), "rupakc/travel-planner", SHA, dark=False)
        self.assertIn("    val Teal700 = Color(0xFF0F766E)\n", out)
        self.assertIn("    val White = Color(0xFFFFFFFF)\n", out)

    def test_dark_object(self):
        out = gen_tokens.render_palette(_tokens(), "rupakc/travel-planner", SHA, dark=True)
        self.assertIn("internal object DarkPalette {", out)
        self.assertIn("    val White = Color(0xFF121A2B)\n", out)

    def test_header_names_pinned_sha(self):
        out = gen_tokens.render_palette(_tokens(), "rupakc/travel-planner", SHA, dark=False)
        self.assertEqual(
            out.splitlines()[0],
            "// Generated by tools/web-sync/gen_tokens.py from rupakc/travel-planner@" + SHA
            + " frontend/design/tokens.json. Do not edit.",
        )

    def test_check_detects_drift(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "config").mkdir()
            (root / "config" / "web-source.properties").write_text(
                "web.repo=rupakc/travel-planner\nweb.sha=" + SHA + "\n")
            self.assertEqual(gen_tokens.run("generate", FIXTURE, root), 0)
            self.assertEqual(gen_tokens.run("check", FIXTURE, root), 0)
            p = root / gen_tokens.PALETTE_PATH
            p.write_text(p.read_text().replace("0F766E", "0F766F"))
            self.assertEqual(gen_tokens.run("check", FIXTURE, root), 1)

    def test_rejects_bad_hex(self):
        t = _tokens()
        t["palette"]["teal"]["700"] = "#12345"
        with self.assertRaises(ValueError):
            gen_tokens.render_palette(t, "r", SHA, dark=False)


if __name__ == "__main__":
    unittest.main()
