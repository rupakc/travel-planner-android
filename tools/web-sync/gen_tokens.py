#!/usr/bin/env python3
"""Generates Palette.kt and DarkPalette.kt from the web repo's frontend/design/tokens.json.

Usage: gen_tokens.py generate|check --tokens <path to tokens.json>
`check` exits 1 and names the stale file when the output differs.
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from websource import read_pin  # noqa: E402

THEME_DIR = Path("core/designsystem/src/main/kotlin/io/github/rupakc/travelplanner/core/designsystem/theme")
PALETTE_PATH = THEME_DIR / "Palette.kt"
DARK_PALETTE_PATH = THEME_DIR / "DarkPalette.kt"
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def _hex(value: str, where: str) -> str:
    if not isinstance(value, str) or not HEX.match(value):
        raise ValueError(f"bad hex {value!r} at {where}")
    return "0xFF" + value[1:].upper()


def _pascal(name: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[-_ ]", name) if p)


def render_palette(tokens: dict, repo: str, sha: str, dark: bool) -> str:
    block = tokens["dark" if dark else "palette"]
    obj = "DarkPalette" if dark else "Palette"
    lines = [
        f"// Generated by tools/web-sync/gen_tokens.py from {repo}@{sha} frontend/design/tokens.json. Do not edit.",
        "package io.github.rupakc.travelplanner.core.designsystem.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        f"internal object {obj} {{",
    ]
    for family, value in block.items():
        if family.startswith("$"):
            continue
        if isinstance(value, dict):
            for stop in sorted(value, key=int):
                lines.append(f"    val {_pascal(family)}{stop} = Color({_hex(value[stop], f'{family}.{stop}')})")
        else:
            lines.append(f"    val {_pascal(family)} = Color({_hex(value, family)})")
    lines.append("}")
    return "\n".join(lines) + "\n"


def run(command: str, tokens_path: Path, root: Path) -> int:
    repo, sha = read_pin(root)
    tokens = json.loads(Path(tokens_path).read_text())
    outputs = {
        PALETTE_PATH: render_palette(tokens, repo, sha, dark=False),
        DARK_PALETTE_PATH: render_palette(tokens, repo, sha, dark=True),
    }
    stale = 0
    for rel, text in outputs.items():
        target = root / rel
        if command == "generate":
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        elif not target.exists() or target.read_text() != text:
            print(f"stale: {rel}")
            stale = 1
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["generate", "check"])
    parser.add_argument("--tokens", required=True, type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    return run(args.command, args.tokens, root)


if __name__ == "__main__":
    sys.exit(main())
